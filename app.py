
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import plotly.express as px
import streamlit as st
from sklearn.metrics import confusion_matrix

st.set_page_config(
    page_title="NetSentinel",
    page_icon="🛡️",
    layout="wide",
)

MODEL_PATH = Path("models/netsentinel.joblib")

st.title("🛡️ NetSentinel")
st.caption("Network Traffic Intelligence & Intrusion Detection")

if not MODEL_PATH.exists():
    st.error("Model not found. Run python train_model.py first.")
    st.stop()

saved = joblib.load(MODEL_PATH)
model = saved["pipeline"]
features = saved["features"]

@st.cache_data
def load_sample():
    files = list(Path("data").rglob("*.csv"))
    if not files:
        return pd.DataFrame()
    df = pd.read_csv(files[0], encoding="latin1", low_memory=False)
    df.columns = df.columns.str.strip()
    return df

data = load_sample()

overview, predict, live = st.tabs([
    "Overview", "Prediction Lab", "Live Analysis"
])

with overview:
    st.subheader("Dataset Overview")

    if not data.empty and "Label" in data.columns:
        labels = data["Label"].astype(str).str.strip()
        c1, c2, c3 = st.columns(3)

        c1.metric("Records in sample", f"{len(data):,}")
        c2.metric("Traffic features", len(features))
        c3.metric("Attack types", labels.nunique() - int(
            labels.str.upper().eq("BENIGN").any()
        ))

        counts = labels.value_counts().rename_axis("Label").reset_index(
            name="Records"
        )
        fig = px.bar(
            counts,
            x="Label",
            y="Records",
            title="Traffic Label Distribution",
            color="Label",
        )
        st.plotly_chart(fig, use_container_width=True)
    else:
        st.warning("No sample dataset found.")

    st.info(
        "Predictions are generated by the trained historical-data model. "
        "This dashboard does not yet capture live traffic."
    )

with predict:
    st.subheader("Analyze Network Flows")
    st.write(
        "Upload a CIC-IDS2017-compatible CSV containing the model's "
        "numeric input features."
    )

    upload = st.file_uploader("Upload network flow CSV", type=["csv"])

    if upload:
        incoming = pd.read_csv(upload, encoding="latin1", low_memory=False)
        incoming.columns = incoming.columns.str.strip()

        missing = [f for f in features if f not in incoming.columns]

        if missing:
            st.error(
                f"CSV is missing {len(missing)} required features. "
                f"Examples: {missing[:8]}"
            )
        else:
            X = incoming[features].apply(pd.to_numeric, errors="coerce")
            X = X.replace([np.inf, -np.inf], np.nan)

            predictions = model.predict(X)
            probabilities = model.predict_proba(X)[:, 1]

            results = incoming.copy()
            results["Prediction"] = np.where(
                predictions == 1, "ATTACK", "BENIGN"
            )
            results["Attack probability"] = probabilities

            attacks = int((predictions == 1).sum())
            c1, c2, c3 = st.columns(3)
            c1.metric("Flows analyzed", f"{len(results):,}")
            c2.metric("Predicted attacks", f"{attacks:,}")
            c3.metric("Predicted benign", f"{len(results)-attacks:,}")

            st.plotly_chart(
                px.histogram(
                    results,
                    x="Prediction",
                    color="Prediction",
                    title="Predicted Traffic Classes",
                ),
                use_container_width=True,
            )

            st.dataframe(results.head(500), use_container_width=True)

            st.download_button(
                "Download predictions CSV",
                results.to_csv(index=False).encode("utf-8"),
                file_name="netsentinel_predictions.csv",
                mime="text/csv",
            )

with live:
    st.subheader("Live Network Analysis")
    st.warning("Live capture is not connected yet.")
    st.write(
        "Next milestone: capture authorized local traffic, extract compatible "
        "flow features, and pass completed flows to the trained model."
    )
    st.caption(
        "For now, use the Prediction Lab to analyze historical flow CSVs."
    )
